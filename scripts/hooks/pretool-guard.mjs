// PreToolUse guard. Exit 2 (reason on stderr) blocks the tool call.
// Blocks: hand-writes to docs/evidence/** (only scripts/evidence.mjs writes there; requirements*.json are hand-written),
// git push --force / --force-with-lease, and any read or write of .env files.
import { fileURLToPath } from "node:url";
import path from "node:path";

const norm = (p) => String(p ?? "").replace(/\\/g, "/");

function isEnvPath(p) {
  const base = norm(p).split("/").pop() ?? "";
  return /^\.env(\..+)?$/.test(base) && !/\.(example|sample|template)$/i.test(base);
}

function commandTouchesEnv(cmd) {
  const re = /(^|[\s"'=/<>])(\.env(?:\.[A-Za-z0-9_-]+)?)(?=$|[\s"';|&<>)])/g;
  for (const m of cmd.matchAll(re)) {
    if (!/\.(example|sample|template)$/i.test(m[2])) return true;
  }
  return false;
}

function isEvidencePath(p) {
  const n = norm(p);
  if (!/(^|\/)docs\/evidence(\/|$)/.test(n)) return false;
  return !/(^|\/)docs\/evidence\/requirements(-[a-z0-9-]+)?\.json$/.test(n);
}

/** Returns a reason string if the call must be blocked, otherwise null. */
export function evaluate(payload) {
  const tool = payload?.tool_name;
  const input = payload?.tool_input ?? {};
  const file = input.file_path ?? input.notebook_path ?? input.path;
  if (file) {
    if (isEnvPath(file)) return `blocked: ${tool} on a .env file (${norm(file)}). Secrets stay out of the session.`;
    if (["Write", "Edit", "MultiEdit", "NotebookEdit"].includes(tool) && isEvidencePath(file)) {
      return `blocked: do not hand-write ${norm(file)}. Evidence is generated by scripts/evidence.mjs (npm run evidence).`;
    }
  }
  if (tool === "Bash") {
    const cmd = norm(input.command);
    if (/\bgit\b[^|;&\n]*\bpush\b[^|;&\n]*(--force\b|--force-with-lease|\s-f\b|\s\+\S)/.test(cmd)) {
      return "blocked: force push is not allowed (lab rule: never rewrite history after tagging).";
    }
    if (commandTouchesEnv(cmd)) return "blocked: command touches a .env file.";
    const writes = /(>>?|\btee\b(\s+-a)?)\s*["']?[^|;&\n]*docs\/evidence/;
    const verbs = /\b(cp|mv|rm|sed\s+-i|Set-Content|Out-File|Add-Content|Remove-Item|Copy-Item|Move-Item|truncate)\b[^|;&\n]*docs\/evidence/;
    if (writes.test(cmd) || verbs.test(cmd)) {
      return "blocked: do not write to docs/evidence/** from the shell. Run npm run evidence instead.";
    }
  }
  return null;
}

async function main() {
  let raw = "";
  for await (const chunk of process.stdin) raw += chunk;
  let payload = {};
  try {
    payload = JSON.parse(raw || "{}");
  } catch {
    process.exit(0); // not our job to break the session on bad input
  }
  const reason = evaluate(payload);
  if (reason) {
    process.stderr.write(reason + "\n");
    process.exit(2);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
